//! # iris-voxel
//!
//! 类 Minecraft 体素沙盒的首个可玩闭环，同时是引擎的 dogfooding 项目。
//!
//! 世界固定为 8×8 个区块，每区块 16×16×48 方块并全部常驻。游戏实现
//! 确定性地形与洞穴、洞口坡道、矿石矿脉、疏林与洞穴荧光石，以及面剔除
//! 区块网格、16×16 手绘风图集、天空光与方块光传播、平滑光照与逐顶点
//! 环境光遮蔽、区域色调染色、平色天空与方块云、GTAO 接触阴影、胶囊
//! 碰撞、DDA 方块拾取、破坏与放置、按方块计数的背包、深色玻璃 HUD。
//! 破坏方块按掉落表进入背包，放置消耗一格。
//!
//! 移动是「重」的体素手感：重力按 2.8 倍标准重力积分（约 27.5 m/s²）、
//! 下落上限 30 m/s、跳跃顶点 1.24 格；按住 Shift 且有前进输入即奔跑，
//! 水平速度提高三成并轻微外扩视场角。
//!
//! 树叶是 alpha 裁切方块：贴图挖出成块孔洞，网格按材质拆成不透明与
//! 裁切两套，光穿过叶片只多衰减一级。
//!
//! 画风参考 `bevy_demo`（BLOCKWILD）：低饱和底色 + 颗粒 + 簇状细节的
//! 图集、整片淡蓝的平色天空与近白方块云、墨绿玻璃 HUD。
//!
//! 纯玩法核心在 [`logic`] 中，只依赖 glam 与标准库；引擎资源与系统
//! 接线在 [`plugin`] 中。本轮仍不提供玻璃与水的透光、彩色光源、昼夜
//! 循环、存档、流式加载、流体或生物。

